"""
validate_synthetic.py
Validates the four synthetic CSV files generated by generate_synthetic.py.

Exit codes:
  0 — All checks passed
  1 — One or more checks failed (details printed to stdout)

Run from project root:
    python3 data/validate_synthetic.py
"""

import csv
import os
import sys
from datetime import date, datetime, timedelta

# ---------------------------------------------------------------------------
# Config (mirrors generate_synthetic.py)
# ---------------------------------------------------------------------------

DATA_DIR     = os.path.join(os.path.dirname(__file__), "synthetic")
WINDOW_START = date(2026, 8, 3)
WINDOW_END   = date(2026, 10, 25)

EXPENSE_CATEGORIES = {"convenience_food", "groceries", "transport", "shopping", "bills", "other"}
TASK_CATEGORIES    = {"work", "personal", "health", "finance", "household"}

EXPENSE_SCHEMA = ["id", "persona_id", "date", "amount", "category", "description"]
TASK_SCHEMA    = ["id", "persona_id", "title", "created_at", "due_date", "completed_at", "category"]

FILES = {
    "maya_expenses":  ("maya-001", "expense"),
    "arjun_expenses": ("arjun-001", "expense"),
    "maya_tasks":     ("maya-001", "task"),
    "arjun_tasks":    ("arjun-001", "task"),
}


def week_mondays():
    mondays, d = [], WINDOW_START
    while d <= WINDOW_END:
        mondays.append(d)
        d += timedelta(weeks=1)
    return mondays


WEEK_MONDAYS = week_mondays()


def week_sunday(monday: date) -> date:
    return monday + timedelta(days=6)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

errors  = []
results = []


def fail(msg: str):
    errors.append(msg)


def ok(msg: str):
    results.append(f"  ✓ {msg}")


def load_csv(name: str) -> list:
    path = os.path.join(DATA_DIR, f"{name}.csv")
    if not os.path.exists(path):
        fail(f"File not found: {path}")
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


# ---------------------------------------------------------------------------
# Schema validation
# ---------------------------------------------------------------------------

def validate_schema(rows: list, expected_cols: list, file_name: str):
    if not rows:
        fail(f"{file_name}: no rows (file may be empty or missing)")
        return
    actual = list(rows[0].keys())
    if actual != expected_cols:
        fail(f"{file_name}: schema mismatch\n    Expected: {expected_cols}\n    Got     : {actual}")
    else:
        ok(f"{file_name}: schema correct ({len(expected_cols)} columns)")


# ---------------------------------------------------------------------------
# Duplicate IDs
# ---------------------------------------------------------------------------

def validate_no_duplicate_ids(rows: list, file_name: str):
    ids = [r["id"] for r in rows]
    dupes = [i for i in ids if ids.count(i) > 1]
    if dupes:
        fail(f"{file_name}: duplicate IDs: {set(dupes)}")
    else:
        ok(f"{file_name}: no duplicate IDs")


# ---------------------------------------------------------------------------
# Date format
# ---------------------------------------------------------------------------

def is_valid_date(s: str) -> bool:
    try:
        date.fromisoformat(s)
        return True
    except ValueError:
        return False


def is_valid_datetime(s: str) -> bool:
    try:
        datetime.fromisoformat(s)
        return True
    except ValueError:
        return False


def validate_dates_expenses(rows: list, file_name: str):
    bad = [r["id"] for r in rows if not is_valid_date(r.get("date", ""))]
    if bad:
        fail(f"{file_name}: invalid dates in {len(bad)} record(s): {bad[:5]}")
    else:
        ok(f"{file_name}: all dates valid ISO format")


def validate_dates_tasks(rows: list, file_name: str):
    bad = []
    for r in rows:
        if not is_valid_datetime(r.get("created_at", "")):
            bad.append(("created_at", r["id"]))
        if not is_valid_date(r.get("due_date", "")):
            bad.append(("due_date", r["id"]))
        comp = r.get("completed_at", "")
        if comp and not is_valid_datetime(comp):
            bad.append(("completed_at", r["id"]))
    if bad:
        fail(f"{file_name}: invalid date fields in {len(bad)} record(s): {bad[:5]}")
    else:
        ok(f"{file_name}: all date fields valid ISO format")


# ---------------------------------------------------------------------------
# Non-negative amounts
# ---------------------------------------------------------------------------

def validate_non_negative_amounts(rows: list, file_name: str):
    bad = []
    for r in rows:
        try:
            if float(r["amount"]) < 0:
                bad.append(r["id"])
        except (ValueError, KeyError):
            bad.append(r.get("id", "?"))
    if bad:
        fail(f"{file_name}: negative amounts in {len(bad)} record(s): {bad[:5]}")
    else:
        ok(f"{file_name}: all amounts non-negative")


# ---------------------------------------------------------------------------
# Category values
# ---------------------------------------------------------------------------

def validate_categories_expenses(rows: list, file_name: str):
    bad = [r["id"] for r in rows if r.get("category") not in EXPENSE_CATEGORIES]
    if bad:
        fail(f"{file_name}: invalid categories in {len(bad)} record(s): {bad[:5]}")
    else:
        ok(f"{file_name}: all expense categories valid")


def validate_categories_tasks(rows: list, file_name: str):
    bad = [r["id"] for r in rows if r.get("category") not in TASK_CATEGORIES]
    if bad:
        fail(f"{file_name}: invalid categories in {len(bad)} record(s): {bad[:5]}")
    else:
        ok(f"{file_name}: all task categories valid")


# ---------------------------------------------------------------------------
# Task temporal constraints
# ---------------------------------------------------------------------------

def validate_task_dates(rows: list, file_name: str):
    """
    Validate:
      1. created_at <= due_date  (documented exception: none expected)
      2. completed_at >= created_at  (when present)
    """
    created_after_due = []
    completed_before_created = []

    for r in rows:
        try:
            created_dt = datetime.fromisoformat(r["created_at"])
            due_d      = date.fromisoformat(r["due_date"])
            due_dt     = datetime(due_d.year, due_d.month, due_d.day, 23, 59, 59)

            if created_dt > due_dt:
                created_after_due.append(r["id"])

            comp = r.get("completed_at", "")
            if comp:
                comp_dt = datetime.fromisoformat(comp)
                if comp_dt < created_dt:
                    completed_before_created.append(r["id"])
        except (ValueError, KeyError):
            pass  # Already caught by date format validation

    if created_after_due:
        fail(f"{file_name}: created_at > due_date in {len(created_after_due)} task(s): "
             f"{created_after_due[:5]}")
    else:
        ok(f"{file_name}: created_at <= due_date for all tasks")

    if completed_before_created:
        fail(f"{file_name}: completed_at < created_at in {len(completed_before_created)} task(s): "
             f"{completed_before_created[:5]}")
    else:
        ok(f"{file_name}: completed_at >= created_at for all completed tasks")


# ---------------------------------------------------------------------------
# Week coverage
# ---------------------------------------------------------------------------

def validate_week_coverage_expenses(rows: list, file_name: str):
    covered = set()
    for r in rows:
        try:
            d = date.fromisoformat(r["date"])
            for week_idx, monday in enumerate(WEEK_MONDAYS):
                if monday <= d <= week_sunday(monday):
                    covered.add(week_idx)
                    break
        except ValueError:
            pass
    missing = [i for i in range(12) if i not in covered]
    if missing:
        fail(f"{file_name}: weeks missing from expenses: {[i+1 for i in missing]}")
    else:
        ok(f"{file_name}: all 12 weeks have expense records")


def validate_week_coverage_tasks(rows: list, file_name: str):
    covered = set()
    for r in rows:
        try:
            # Use due_date for week coverage check
            d = date.fromisoformat(r["due_date"])
            if WINDOW_START <= d <= WINDOW_END:
                for week_idx, monday in enumerate(WEEK_MONDAYS):
                    if monday <= d <= week_sunday(monday):
                        covered.add(week_idx)
                        break
        except ValueError:
            pass
    # Tasks may have due dates spread across fewer weeks due to future tasks
    # We require at least 10/12 weeks to have tasks due
    if len(covered) < 10:
        fail(f"{file_name}: only {len(covered)} of 12 weeks have tasks due (need ≥10)")
    else:
        ok(f"{file_name}: {len(covered)}/12 weeks have task due-dates")


# ---------------------------------------------------------------------------
# Planted pattern — insight ratio
# ---------------------------------------------------------------------------

def compute_insight_ratio(expenses: list, tasks: list, persona_id: str):
    """
    Overdue at end-of-week snapshot for week_idx:
      task.due_date in [monday, sunday] of that week
      AND (completed_at == "" OR completed_at > due_date)
    """
    persona_tasks    = [t for t in tasks    if t.get("persona_id") == persona_id]
    persona_expenses = [e for e in expenses if e.get("persona_id") == persona_id]

    week_overdue = {}
    for week_idx, monday in enumerate(WEEK_MONDAYS):
        sunday = week_sunday(monday)
        count  = 0
        for t in persona_tasks:
            try:
                due_d = date.fromisoformat(t["due_date"])
            except ValueError:
                continue
            if due_d > sunday:
                continue
            comp = t.get("completed_at", "")
            if comp == "":
                count += 1
            else:
                try:
                    comp_d = datetime.fromisoformat(comp).date()
                    if comp_d > sunday:
                        count += 1
                except ValueError:
                    pass
        week_overdue[week_idx] = count

    week_cf = {i: 0.0 for i in range(12)}
    for e in persona_expenses:
        if e.get("category") != "convenience_food":
            continue
        try:
            d = date.fromisoformat(e["date"])
        except ValueError:
            continue
        for week_idx, monday in enumerate(WEEK_MONDAYS):
            if monday <= d <= week_sunday(monday):
                week_cf[week_idx] += float(e["amount"])
                break

    qualifying = [i for i, c in week_overdue.items() if c >= 3]
    baseline   = [i for i, c in week_overdue.items() if c < 3]

    avg_qual = sum(week_cf[i] for i in qualifying) / len(qualifying) if qualifying else 0
    avg_base = sum(week_cf[i] for i in baseline)   / len(baseline)   if baseline  else 0
    ratio    = avg_qual / avg_base if avg_base > 0 else float("inf")

    return ratio, avg_qual, avg_base, len(qualifying), len(baseline), week_overdue


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("=" * 65)
    print("Life, Decoded — Synthetic Data Validator")
    print(f"Window: {WINDOW_START} → {WINDOW_END}  ({len(WEEK_MONDAYS)} weeks)")
    print("=" * 65)

    # Load files
    maya_exp   = load_csv("maya_expenses")
    maya_tasks = load_csv("maya_tasks")
    arjun_exp  = load_csv("arjun_expenses")
    arjun_tsk  = load_csv("arjun_tasks")

    print("\n--- Schema validation ---")
    validate_schema(maya_exp,   EXPENSE_SCHEMA, "maya_expenses")
    validate_schema(arjun_exp,  EXPENSE_SCHEMA, "arjun_expenses")
    validate_schema(maya_tasks, TASK_SCHEMA,    "maya_tasks")
    validate_schema(arjun_tsk,  TASK_SCHEMA,    "arjun_tasks")

    print("\n--- Duplicate ID checks ---")
    validate_no_duplicate_ids(maya_exp,   "maya_expenses")
    validate_no_duplicate_ids(arjun_exp,  "arjun_expenses")
    validate_no_duplicate_ids(maya_tasks, "maya_tasks")
    validate_no_duplicate_ids(arjun_tsk,  "arjun_tasks")

    print("\n--- Date format checks ---")
    validate_dates_expenses(maya_exp,   "maya_expenses")
    validate_dates_expenses(arjun_exp,  "arjun_expenses")
    validate_dates_tasks(maya_tasks,    "maya_tasks")
    validate_dates_tasks(arjun_tsk,     "arjun_tasks")

    print("\n--- Non-negative amounts ---")
    validate_non_negative_amounts(maya_exp,  "maya_expenses")
    validate_non_negative_amounts(arjun_exp, "arjun_expenses")

    print("\n--- Category values ---")
    validate_categories_expenses(maya_exp,   "maya_expenses")
    validate_categories_expenses(arjun_exp,  "arjun_expenses")
    validate_categories_tasks(maya_tasks,    "maya_tasks")
    validate_categories_tasks(arjun_tsk,     "arjun_tasks")

    print("\n--- Task temporal constraints ---")
    validate_task_dates(maya_tasks, "maya_tasks")
    validate_task_dates(arjun_tsk,  "arjun_tasks")

    print("\n--- Week coverage ---")
    validate_week_coverage_expenses(maya_exp,   "maya_expenses")
    validate_week_coverage_expenses(arjun_exp,  "arjun_expenses")
    validate_week_coverage_tasks(maya_tasks,    "maya_tasks")
    validate_week_coverage_tasks(arjun_tsk,     "arjun_tasks")

    print("\n--- Planted pattern / insight ratios ---")

    all_exp  = maya_exp + arjun_exp
    all_task = maya_tasks + arjun_tsk

    for label, pid in [("Maya", "maya-001"), ("Arjun", "arjun-001")]:
        ratio, avg_qual, avg_base, n_qual, n_base, week_ov = compute_insight_ratio(
            all_exp, all_task, pid
        )

        print(f"\n  [{label}]")
        print(f"    Per-week overdue counts : {[week_ov[i] for i in range(12)]}")
        print(f"    Qualifying weeks (≥3)   : {n_qual}")
        print(f"    Baseline weeks   (<3)   : {n_base}")
        print(f"    Avg CF (qualifying)     : ₹{avg_qual:,.2f}/week")
        print(f"    Avg CF (baseline)       : ₹{avg_base:,.2f}/week")
        print(f"    Ratio                   : {ratio:.2f}x")

        if ratio < 1.5:
            fail(f"{label}: planted pattern ratio {ratio:.2f}x is below 1.5x threshold")
        else:
            ok(f"{label}: pattern ratio {ratio:.2f}x ≥ 1.5x")

        if n_qual < 3:
            fail(f"{label}: only {n_qual} qualifying weeks (need ≥3)")
        else:
            ok(f"{label}: {n_qual} qualifying weeks ≥ 3")

        if n_base < 3:
            fail(f"{label}: only {n_base} baseline weeks (need ≥3)")
        else:
            ok(f"{label}: {n_base} baseline weeks ≥ 3")

    # Print collected success messages
    print("\n--- Results ---")
    for msg in results:
        print(msg)

    # Final verdict
    print()
    if errors:
        print(f"FAILED — {len(errors)} error(s):")
        for e in errors:
            print(f"  ✗ {e}")
        sys.exit(1)
    else:
        print(f"ALL CHECKS PASSED ({len(results)} checks)")
        sys.exit(0)


if __name__ == "__main__":
    main()
